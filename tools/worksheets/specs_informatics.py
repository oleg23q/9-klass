def graph(edges):
    g: dict[str, dict[str, int]] = {}
    for a, b, w in edges:
        g.setdefault(a, {})[b] = w
        g.setdefault(b, {})[a] = w
    return g


def shortest(g, start, end, ban=None):
    dist = {start: 0}
    heap = [(0, start)]
    while heap:
        d, v = heapq.heappop(heap)
        if d > dist[v]:
            continue
        for u, w in g[v].items():
            if u == ban:
                continue
            if d + w < dist.get(u, 10**9):
                dist[u] = d + w
                heapq.heappush(heap, (d + w, u))
    return dist.get(end)


def all_paths(g, start, end, ban=None):
    result = []

    def walk(current, path, length):
        if current == end:
            result.append((path, length))
            return
        for nxt, w in g[current].items():
            if nxt not in path and nxt != ban:
                walk(nxt, path + [nxt], length + w)

    walk(start, [start], 0)
    return sorted(result, key=lambda item: (item[1], len(item[0])))


def fmt_path(path):
    return "→".join(path)


def vertices(edges):
    return sorted({v for a, b, _ in edges for v in (a, b)})


def road_table(edges) -> str:
    names = vertices(edges)
    weights = {frozenset((a, b)): w for a, b, w in edges}
    head = "".join(f"<th>{n}</th>" for n in names)
    rows = []
    for r in names:
        cells = []
        for c in names:
            if r == c:
                cells.append('<td class="diag"></td>')
            else:
                w = weights.get(frozenset((r, c)))
                cells.append(f"<td>{'' if w is None else w}</td>")
        rows.append(f"<tr><th>{r}</th>{''.join(cells)}</tr>")
    return f'<table class="data"><tr><th></th>{head}</tr>{"".join(rows)}</table>'


# DAG для урока 06: ориентированные рёбра, старт — первая вершина.
def dag_counts(edges, names):
    counts = {}
    for index, name in enumerate(names):
        if index == 0:
            counts[name] = 1
        else:
            counts[name] = sum(counts[a] for a, b in edges if b == name)
    return counts


def dag_paths(edges, start, end):
    adj: dict[str, list[str]] = {}
    for a, b in edges:
        adj.setdefault(a, []).append(b)
    out = []

    def walk(current, path):
        if current == end:
            out.append(path)
            return
        for nxt in adj.get(current, []):
            walk(nxt, path + [nxt])

    walk(start, [start])
    return out


