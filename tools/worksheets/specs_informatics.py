def pick(variant: str, a, b):
    return a if variant == "А" else b


def run(code: str) -> str:
    """Выполняет учебный фрагмент и возвращает текст, который он вывел (код пишет автор листа, не ученик)."""
    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        exec(code, {})
    return buffer.getvalue().rstrip("\n")


def lines_answer(text: str) -> str:
    return text.replace("\n", "; ")


def road_word(n: int) -> str:
    return "дорога" if n % 10 == 1 and n % 100 != 11 else "дороги" if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14 else "дорог"


def count_word(n: int) -> str:
    return "путь" if n % 10 == 1 and n % 100 != 11 else "пути" if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14 else "путей"


