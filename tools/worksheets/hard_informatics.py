def _bin(names, es, directed):
    n = len(names)
    m = [[0] * n for _ in range(n)]
    for a, b in es:
        m[names.index(a)][names.index(b)] = 1
        if not directed:
            m[names.index(b)][names.index(a)] = 1
    return m


