def known_sum_text(formula: str, element: str) -> str:
    from .chem_utils import KNOWN
    counts = parse(formula)
    parts = [f"{e}: {ox(KNOWN[e])} · {n} = {ox(KNOWN[e] * n)}" for e, n in counts.items() if e != element]
    return "; ".join(parts)


def c05(v):
    simple = pick(v, ["O2", "Fe", "H2"], ["N2", "Cu", "Cl2"])
    find = pick(v, [("SO3", "S"), ("NH3", "N")], [("CO2", "C"), ("KMnO4", "Mn")])
    pair = pick(v, ("NaOH + HCl → NaCl + H₂O", ["Mg", "O2"], ["MgO"]), ("CaO + H₂O → Ca(OH)₂", ["Na", "Cl2"], ["NaCl"]))
    # Изменения степеней окисления: (элемент, было, стало); значения проверяются расчётом.
    red = pick(v, (["Zn", "HCl"], ["ZnCl2", "H2"], [("Zn", 0, 2), ("H", 1, 0)]), (["Fe", "CuSO4"], ["FeSO4", "Cu"], [("Fe", 0, 2), ("Cu", 2, 0)]))
    redox = pick(v, (["CuO", "H2"], ["Cu", "H2O"], [("Cu", 2, 0), ("H", 0, 1)]), (["Fe2O3", "CO"], ["Fe", "CO2"], [("Fe", 3, 0), ("C", 2, 4)]))
    assert oxidation("CuO", "Cu") == 2 and oxidation("Fe2O3", "Fe") == 3 and oxidation("CO", "C") == 2 and oxidation("CO2", "C") == 4
    assert oxidation("HCl", "Cl", {"H": 1}) == -1 and oxidation("ZnCl2", "Zn", {"Cl": -1}) == 2 and oxidation("CuSO4", "Cu", {"S": 6}) == 2
    el1, n1, el2, a2, n2 = pick(v, ("Al", 3, "Cu", 2, 2), ("Mg", 2, "Fe", 3, 3))
    final = pick(v, (["Al", "CuO"], ["Al2O3", "Cu"]), (["Mg", "Fe2O3"], ["MgO", "Fe"]))
    tasks = [N("Назови степени окисления элементов в веществах: " + ", ".join(pretty(f) for f in simple) + ".", "; ".join(f"{pretty(f)}: 0" for f in simple),
               ["В простых веществах степень окисления равна 0."], [("степень окисления простого вещества названа не нулём", "С: правило для простых веществ не применено")], work="short", label="Ответ")]
    for f, e in find:
        value = oxidation(f, e)
        tasks.append(N(f"Найди степень окисления элемента {e} в веществе {pretty(f)}.", ox(value),
                       ["Сумма степеней окисления в нейтральном веществе равна 0.", known_sum_text(f, e) + f"; значит {e} = {ox(value)}."],
                       [(ox(-value), "С: знак степени окисления перепутан"), ("0", "С: степень окисления принята равной нулю")], work="solve"))
    tasks.append(V(f"Какая реакция является ОВР и почему? 1) {pair[0]}; 2) {scheme(pair[1], pair[2])}.",
                   "вторая: в ней меняются степени окисления элементов (простые вещества превращаются в соединения); в первой степени окисления не меняются",
                   ["ОВР сопровождается изменением степеней окисления.", "В реакции без простых веществ среди участников степени окисления обычно не меняются."],
                   [("«обе реакции ОВР»", "С: не проверено изменение степеней окисления")]))
    r, p_, ch = red
    tasks.append(V(f"В реакции {scheme(r, p_)} (после уравнивания) укажи, что окисляется и что восстанавливается.",
                   "; ".join(f"{e}: {ox(a)} → {ox(b)} ({'окисляется' if b > a else 'восстанавливается'})" for e, a, b in ch),
                   ["Степень окисления растёт — вещество окисляется; уменьшается — восстанавливается."] + [f"{e}: {ox(a)} → {ox(b)}" for e, a, b in ch],
                   [("окисление и восстановление перепутаны", "П: направление изменения степени окисления не определено")]))
    r2, p2, ch2 = redox
    ox_el = next(e for e, a, b in ch2 if b < a)
    red_el = next(e for e, a, b in ch2 if b > a)
    tasks.append(V(f"В реакции {scheme(r2, p2)} назови окислитель и восстановитель.",
                   f"окислитель — вещество с элементом {ox_el} (степень окисления уменьшается); восстановитель — вещество с элементом {red_el} (степень окисления растёт)",
                   [f"{e}: {ox(a)} → {ox(b)}" for e, a, b in ch2] + ["Окислитель принимает электроны, восстановитель отдаёт."], [("окислитель и восстановитель перепутаны", "П: окислитель принимает электроны")]))
    lcm = n1 * n2 // gcd(n1, n2)
    tasks.append(N(f"Для переходов {el1}⁰ − {n1}e⁻ → {el1}⁺{str(n1).translate(SUP)} и {el2}⁺{str(a2).translate(SUP)} + {n2}e⁻ → {el2}⁰ подбери множители, чтобы число электронов совпало.",
                   f"множители: {lcm // n1} и {lcm // n2}; общее число электронов {lcm}",
                   [f"НОК({n1}; {n2}) = {lcm}.", f"{lcm}/{n1} = {lcm // n1}, {lcm}/{n2} = {lcm // n2}."], [(f"{n1} и {n2}", "У: множители взяты равными числу электронов")], work="solve"))
    coefs, text = balanced(final[0], final[1])
    tasks.append(N(f"Расставь коэффициенты методом электронного баланса: {scheme(final[0], final[1])}.", text,
                   ["Электронный баланс: общее число электронов — НОК, затем проверка атомов.", f"Уравнение: {text}."],
                   [(scheme(final[0], final[1]), "У: коэффициенты не расставлены")], work="solve"))
    tasks.append(V("Закончи фразы: «Восстановитель ... электроны и сам ... . Окислитель ... электроны и сам ...».", "восстановитель отдаёт электроны и сам окисляется; окислитель принимает электроны и сам восстанавливается",
                   ["Восстановитель отдаёт электроны — окисляется; окислитель принимает — восстанавливается."], [("«восстановитель принимает электроны»", "П: термины перепутаны")]))
    return tasks


